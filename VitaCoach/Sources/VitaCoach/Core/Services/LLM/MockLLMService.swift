import Foundation

/// Локальная имитация LLM — отвечает на основе переданного контекста
/// (профиль, метрики, база знаний), без сети. Полезна для офлайн-демо
/// и как фолбэк, пока не подключён реальный провайдер.
struct MockLLMService: LLMService {
    var displayName: String { "VitaCoach (демо-модель)" }

    func complete(messages: [LLMMessage]) async throws -> String {
        try? await Task.sleep(nanoseconds: 350_000_000)

        let lastUser = messages.last { $0.role == .user }?.content.lowercased() ?? ""
        let context = messages.first { $0.role == .system }?.content ?? ""

        if lastUser.contains("план") || lastUser.contains("трениров") {
            return """
            На основе ваших данных рекомендую 3 тренировки в неделю по принципу FITT.
            Начните с базовых движений: приседания, отжимания, выпады и планка.
            Прогрессируйте объёмом ~10% в неделю. Это согласуется с рекомендациями ВОЗ \
            (≥150 мин активности в неделю) и ACSM.

            Хотите, я сгенерирую конкретный план во вкладке «Тренировки»?
            """
        }

        if lastUser.contains("техник") || lastUser.contains("присед") {
            return """
            Главное в технике приседа: колени по линии носков, нейтральная спина, \
            таз отводится назад, глубина — бедро минимум до параллели. \
            Снимите подход на видео во вкладке «Техника» — я разберу углы в суставах \
            и дам точную обратную связь.
            """
        }

        if lastUser.contains("сон") || lastUser.contains("восстанов") {
            return """
            Для восстановления критичен сон: взрослым рекомендовано ≥7 часов (AASM, 2015). \
            Судя по контексту, стоит держать ровный режим и снижать нагрузку при RPE > 8 \
            несколько дней подряд.
            """
        }

        return """
        Я ваш ИИ-тренер. Я вижу ваш профиль и метрики и опираюсь на открытые научные \
        источники (ВОЗ, ACSM, NSCA). Спросите про план тренировок, технику упражнения, \
        питание, сон или восстановление.

        Контекст, который я учитываю:
        \(context.prefix(280))
        """
    }
}
